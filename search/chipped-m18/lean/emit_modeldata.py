# emit_modeldata.py MODEL NAMESPACE : ModelData.lean (vertexQ, c3Perm, mirrorPerm) and the seed / slot data for a C3v
# model with axis (1,1,1) (C3 = cyclic coordinate permutations, mirrors = transpositions), in the C++ vertex order.
import sys
from fractions import Fraction as F
model, ns = sys.argv[1], sys.argv[2]
V=[tuple(F(x) for x in l.split()[2:5]) for l in open(model) if l.startswith('rational_vertex')]
n=len(V); idx={v:i for i,v in enumerate(V)}
def c3(k,v):
    for _ in range(k): v=(v[1],v[2],v[0])
    return v
def mir(i,v):
    v=list(v); a,b=[j for j in range(3) if j!=i]; v[a],v[b]=v[b],v[a]; return tuple(v)
c3p=[[idx[c3(k,v)] for v in V] for k in range(3)]
mp=[[idx[mir(i,v)] for v in V] for i in range(3)]
# seeds: smallest index of each C3 orbit
seeds=[]; seen=set()
for i in range(n):
    if i in seen: continue
    orb={c3p[k][i] for k in range(3)}; seen|=orb; seeds.append(i)
def q(x): return '(%s : ℚ)'%(str(x) if x.denominator==1 else '%d / %d'%(x.numerator,x.denominator))
def row(v): return '![%s]'%', '.join(q(x) for x in v)
L=[]
L.append('module\n\npublic import Mathlib.Data.Fin.VecNotation\npublic import Mathlib.Data.Rat.Defs\n\n@[expose] public section\n')
L.append('/-!\n# The rational model of %s (committed data)\n\nGenerated by search/chipped-m18/lean/emit_modeldata.py from %s: the vertices in the\nC++ order (rational_vertex lines). `c3Perm k` and `mirrorPerm i` are the vertex permutations\ninduced by `c3Mat k` and `mirrorMat i` (coordinate permutations).\n-/\n'%(ns,model.split('/')[-1]))
L.append('namespace %s\n'%ns)
L.append('def vertexQ : Fin %d → Fin 3 → ℚ := ![\n  %s]\n'%(n,',\n  '.join(row(v) for v in V)))
L.append('def c3Perm : Fin 3 → Fin %d → Fin %d := ![%s]\n'%(n,n,', '.join('![%s]'%', '.join(map(str,p)) for p in c3p)))
L.append('def mirrorPerm : Fin 3 → Fin %d → Fin %d := ![%s]\n'%(n,n,', '.join('![%s]'%', '.join(map(str,p)) for p in mp)))
L.append('end %s\n'%ns)
open('ModelData.lean','w').write('\n'.join(L))
print('vertices',n,'seeds (vertexQ indices)',seeds,'slots',3*len(seeds))
for k in range(3):
    print('slot rows k=%d:'%k,[c3p[k][s] for s in seeds])
