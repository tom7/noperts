int main() {
  vec3 c2 = {53756867.0/85983232.0, 373023.0/2686976.0, 494869.0/2097152.0};
  vec3 e10_15 = {V[15].x - V[10].x, V[15].y - V[10].y, V[15].z - V[10].z};

  // We want n such that for all vertices k, dot(n, V[k] - V[10]) <= 0.
  // The normal in 3D orthogonal to u and e10_15 is either +cross(u, e10_15) or -cross(u, e10_15).
  vec3 n1 = cross(c2, e10_15);
  vec3 n2 = { -n1.x, -n1.y, -n1.z };

  std::cout << std::setprecision(10);
  for (int dir = 1; dir <= 2; dir++) {
    vec3 n = (dir == 1) ? n1 : n2;
    std::cout << "--- Direction " << dir << " ---\n";
    int num_pos = 0;
    double max_pos = 0;
    int max_k = -1;
    for (int k = 0; k < 20; k++) {
      vec3 d = {V[k].x - V[10].x, V[k].y - V[10].y, V[k].z - V[10].z};
      double val = dot(n, d);
      std::cout << "  k=" << std::setw(2) << k << ": dot = " << std::setw(15) << val << "\n";
      if (val > 1e-9) {
        num_pos++;
        if (val > max_pos) { max_pos = val; max_k = k; }
      }
    }
    std::cout << "Result: " << num_pos << " positive vertices, max = " << max_pos << " (k=" << max_k << ")\n";
  }

  return 0;
}
