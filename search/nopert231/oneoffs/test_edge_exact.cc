int main() {
  // Cell 031213002112122012121 corners
  vec3 c[3] = {
    {215027467.0/343932928.0, 5968367.0/42991616.0, 1979477.0/8388608.0},
    {215027469.0/343932928.0, 1492091.0/10747904.0, 1979477.0/8388608.0},
    {53756867.0/85983232.0, 373023.0/2686976.0, 494869.0/2097152.0}
  };

  vec3 e10_15 = {V[15].x - V[10].x, V[15].y - V[10].y, V[15].z - V[10].z};

  std::cout << std::setprecision(12);
  for (int ci = 0; ci < 3; ci++) {
    std::cout << "--- Corner " << ci << " ---\n";
    double max_dot_10 = -1e9;
    double max_dot_15 = -1e9;
    int worst_k_10 = -1;
    int worst_k_15 = -1;
    for (int k = 0; k < 20; k++) {
      if (k == 10 || k == 15) continue;
      vec3 d10 = {V[k].x - V[10].x, V[k].y - V[10].y, V[k].z - V[10].z};
      vec3 d15 = {V[k].x - V[15].x, V[k].y - V[15].y, V[k].z - V[15].z};
      double val10 = dot(c[ci], cross(e10_15, d10));
      double val15 = dot(c[ci], cross(e10_15, d15));
      if (val10 > max_dot_10) { max_dot_10 = val10; worst_k_10 = k; }
      if (val15 > max_dot_15) { max_dot_15 = val15; worst_k_15 = k; }
    }
    std::cout << "  with v10: max = " << max_dot_10 << " (vertex " << worst_k_10 << ")\n";
    std::cout << "  with v15: max = " << max_dot_15 << " (vertex " << worst_k_15 << ")\n";
  }

  return 0;
}
