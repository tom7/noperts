#!/usr/bin/env python3
"""Writes the Lean cap table (Noperthedron/.../DHCapData.lean) for the 5D cap
leaves: the base caps (exact frame from capcert's kframe, μ₀, wmax², the
half-turn element H_x for u0) and the images (base, g, s) in exactly the order
of the caps file the search uses (dh_caps.py per base, concatenated).

Usage: dh_cap_lean.py OUT.lean BASE... where BASE = frame_file:mu0:wmax[:prune]"""
import sys
from fractions import Fraction as F
from kfield import K, ico_group

G = ico_group()
def kq(k):
    a, b, c, d = k.v
    def r(q): return f"({q.numerator} : ℚ)" if q.denominator == 1 else f"({q.numerator} / {q.denominator} : ℚ)"
    return f"⟨{r(a)}, {r(b)}, {r(c)}, {r(d)}⟩"
def kvec(v): return "![" + ", ".join(kq(c) for c in v) + "]"

bases, imgs = [], []
for bi, spec in enumerate(sys.argv[2:]):
    parts = spec.split(':')
    path, mu0, wmax = parts[0], F(parts[1]), F(parts[2])
    prune = len(parts) > 3 and parts[3] == 'prune'
    toks = next(l.split()[1:] for l in open(path) if l.startswith('kframe '))
    ks = [K(*map(F, toks[4 * i:4 * i + 4])) for i in range(9)]
    x, e1, e2 = ks[0:3], ks[3:6], ks[6:9]
    gidx = None
    if prune:
        H = tuple(tuple(K(2) * x[i] * x[j] - (K(1) if i == j else K(0)) for j in range(3)) for i in range(3))
        gidx = next(n for n, g in enumerate(G) if g == H)
    bases.append((x, e1, e2, mu0, wmax * wmax, gidx))
    seen = set()
    for n, g in enumerate(G):
        for s in (1, -1):
            img = [[sum((g[i][k] * a[k] for k in range(3)), K()) * s for i in range(3)] for a in (x, e1, e2)]
            key = tuple(c.v for a in img for c in a)
            if key in seen: continue
            seen.add(key)
            imgs.append((bi, n, s > 0))

with open(sys.argv[1], 'w') as f:
    f.write("""module

public import Noperthedron.PentagonalHexecontahedron.CapRow

@[expose] public section

/-!
# The deltoidal hexecontahedron's caps (generated by nopert229 `dh_cap_lean.py`)

The base caps (exact frames, μ₀, wmax², half-turn element) and the images in
the order of the 5D search's caps file (cap leaf `cl <path> <index>`).
-/

namespace Noperthedron.PentagonalHexecontahedron.Cap

def dhCapBases : Array CapBase := #[
""")
    f.write(",\n".join(f"  ⟨{kvec(x)},\n   {kvec(e1)},\n   {kvec(e2)},\n   ({mu0.numerator} / {mu0.denominator} : ℚ), ({w2.numerator} / {w2.denominator} : ℚ), "
                       + (f"some ⟨{gi}, by decide⟩" if gi is not None else "none") + "⟩"
                       for (x, e1, e2, mu0, w2, gi) in bases))
    f.write("]\n\ndef dhCapImgs : Array CapImg := #[\n")
    f.write(",\n".join(f"  ⟨{b}, ⟨{n}, by decide⟩, {'true' if s else 'false'}⟩" for (b, n, s) in imgs))
    f.write("]\n\nend Noperthedron.PentagonalHexecontahedron.Cap\n")
print(f"{len(bases)} bases, {len(imgs)} images", file=sys.stderr)
