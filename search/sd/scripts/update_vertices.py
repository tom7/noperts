"""Install new exact rational vertices into proof/SnubDodecahedron/RationalVertices.lean
(and the seed count in SolidModel.lean).

Reads the rational vertex list exported by the C++ tool codebdd
(model_vertices.lean, by default in $MODEL_DIR) and rewrites
the bodies of `rationalVertices` (all N = 5 S rows) and `seedVertex` (the
first S rows, i.e. orbit 0) in RationalVertices.lean, and the index sizes
(VertexIndex = Fin N, SeedIndex = Fin S); in SolidModel.lean it updates the seed
count S where it is spelled (`Fin S`, `Fin (5 * S)`, `icoOrbitsCheck S`,
`seedCount := S`; the S in prose is not touched). Vertex order is rotation-major
(index = S * orbit + seed), as generated by codebdd.

After this, regenerate the tangent cones with
  python3 scripts/emit_tangent_cones.py ../../proof/SnubDodecahedron/GeneratedTangentCones.lean
and rebuild.
"""

from __future__ import annotations

import argparse
import os
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2] / "proof"  # the Lean project


def read_rows(exported: Path) -> list[str]:
    text = exported.read_text(encoding="utf-8")
    m = re.search(r"def rationalVertices : VertexIndex → Fin 3 → ℚ := !\[\n(.*?)\n\]", text, re.S)
    if not m:
        raise SystemExit(f"{exported}: no rationalVertices definition found")
    rows = [line.strip().rstrip(",") for line in m.group(1).splitlines() if line.strip()]
    if len(rows) % 5 != 0 or not all(r.startswith("![") and r.endswith("]") for r in rows):
        raise SystemExit(f"{exported}: expected 5 * seeds rows, got {len(rows)}")
    return rows


def replace_def(text: str, header: str, rows: list[str]) -> str:
    pattern = re.compile(re.escape(header) + r"\n.*?\n\]", re.S)
    body = header + "\n" + ",\n".join("  " + r for r in rows) + "\n]"
    new, n = pattern.subn(lambda _: body, text, count=1)
    if n != 1:
        raise SystemExit(f"could not find `{header}` in RationalVertices.lean")
    return new


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--exported", type=Path, default=None,
                        help="codebdd's model_vertices.lean (default: $MODEL_DIR/model_vertices.lean)")
    parser.add_argument("--vertices", type=Path,
                        default=REPO / "SnubDodecahedron" / "RationalVertices.lean")
    parser.add_argument("--solid_model", type=Path,
                        default=REPO / "SnubDodecahedron" / "SolidModel.lean")
    args = parser.parse_args()
    if args.exported is None:
        if not os.environ.get("MODEL_DIR"):
            raise SystemExit("pass --exported or set MODEL_DIR to the C++ pipeline directory")
        args.exported = Path(os.environ["MODEL_DIR"]) / "model_vertices.lean"
    rows = read_rows(args.exported)
    text = args.vertices.read_text(encoding="utf-8")
    n, seeds = len(rows), len(rows) // 5
    text = replace_def(text, "def rationalVertices : VertexIndex → Fin 3 → ℚ := ![", rows)
    text = replace_def(text, "def seedVertex : SeedIndex → Fin 3 → ℚ := ![", rows[:seeds])
    # Index sizes: VertexIndex = Fin n, SeedIndex = Fin seeds, index = seeds * k + s.
    for pattern, repl in [(r"abbrev VertexIndex := Fin \d+", f"abbrev VertexIndex := Fin {n}"),
                          (r"abbrev SeedIndex := Fin \d+", f"abbrev SeedIndex := Fin {seeds}")]:
        text, k = re.subn(pattern, repl, text)
        if k != 1:
            raise SystemExit(f"RationalVertices.lean: expected one match for {pattern}, got {k}")
    args.vertices.write_text(text, encoding="utf-8")
    model = args.solid_model.read_text(encoding="utf-8")
    for pattern, repl, count in [
            (r"∀ t : Fin \d+, \(SnubDodecahedron\.seedVertex", f"∀ t : Fin {seeds}, (SnubDodecahedron.seedVertex", 1),
            (r"∀ i : Fin \(5 \* \d+\),", f"∀ i : Fin (5 * {seeds}),", 2),
            (r"icoOrbitsCheck \d+ iOrbitCount", f"icoOrbitsCheck {seeds} iOrbitCount", 1),
            (r"seedCount := \d+\n", f"seedCount := {seeds}\n", 1)]:
        model, k = re.subn(pattern, lambda _, r=repl: r, model)
        if k != count:
            raise SystemExit(f"SolidModel.lean: expected {count} match(es) for {pattern}, got {k}")
    args.solid_model.write_text(model, encoding="utf-8")
    print(f"updated {args.vertices} and {args.solid_model} from {args.exported}")


if __name__ == "__main__":
    main()
