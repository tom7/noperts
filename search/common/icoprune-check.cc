// Checks the icosahedral prune of the 5D search (Lean: AtlasIcoPrune) in
// floating point, independently of the exact quadratic bound:
//
//   neighbors  each of the 12 rounded symmetry neighbors (symmetry-neighbors.h)
//              is a rotation by 72 degrees that maps the model's vertex set
//              to itself, and together they generate a group of 60 rotations
//   cell       random rotations, right-reduced to maximal trace over that
//              group, land in chart 0 (maximal chart trace) with small
//              Cayley coordinates: the extent of the Dirichlet cell
//   leaves     for every pi leaf in the journals, sampled points of its box
//              (inside the Cayley ball) really have trace(R G_n) > trace(R),
//              so no point of the cell is pruned
//
// Usage: icoprune-check.exe [--journals jobs] [--samples N] [--cell_samples N]

#include <array>
#include <cmath>
#include <cstdio>
#include <filesystem>
#include <random>
#include <string>
#include <vector>

#include "base/logging.h"
#include "geom5d.h"
#include "rows5d.h"
#include "symmetry-neighbors.h"
#include "model-vertices.h"

namespace {

// Row-major 3x3 matrices (unlike yocto's column-major mat3).
using M = std::array<double, 9>;

M FromYocto(const geom5d::mat3 &r) {
  M m;
  for (int i = 0; i < 3; i++)
    for (int j = 0; j < 3; j++) m[3 * i + j] = r[j][i];
  return m;
}

M Mul(const M &a, const M &b) {
  M c{};
  for (int i = 0; i < 3; i++)
    for (int j = 0; j < 3; j++)
      for (int k = 0; k < 3; k++) c[3 * i + j] += a[3 * i + k] * b[3 * k + j];
  return c;
}

double Trace(const M &m) { return m[0] + m[4] + m[8]; }

double MaxDiff(const M &a, const M &b) {
  double d = 0;
  for (int k = 0; k < 9; k++) d = std::max(d, std::abs(a[k] - b[k]));
  return d;
}

M Identity() { return {1, 0, 0, 0, 1, 0, 0, 0, 1}; }

M Neighbor(int n) {
  M g;
  for (int k = 0; k < 9; k++) g[k] = (double)SYMMETRY_NEIGHBOR_NUM[n][k] / SYMMETRY_NEIGHBOR_DENOM;
  return g;
}

M RandomRotation(std::mt19937_64 &rng) {
  std::normal_distribution<double> nd;
  double q[4], s = 0;
  for (double &x : q) {
    x = nd(rng);
    s += x * x;
  }
  s = std::sqrt(s);
  const double w = q[0] / s, x = q[1] / s, y = q[2] / s, z = q[3] / s;
  return {1 - 2 * (y * y + z * z), 2 * (x * y - w * z),     2 * (x * z + w * y),
          2 * (x * y + w * z),     1 - 2 * (x * x + z * z), 2 * (y * z - w * x),
          2 * (x * z - w * y),     2 * (y * z + w * x),     1 - 2 * (x * x + y * y)};
}

bool CheckNeighbors(std::vector<M> *group) {
  bool ok = true;
  for (int n = 0; n < NUM_SYMMETRY_NEIGHBORS; n++) {
    const M g = Neighbor(n);
    M gt;
    for (int i = 0; i < 3; i++)
      for (int j = 0; j < 3; j++) gt[3 * i + j] = g[3 * j + i];
    const double orth = MaxDiff(Mul(gt, g), Identity());
    const double det = g[0] * (g[4] * g[8] - g[5] * g[7]) - g[1] * (g[3] * g[8] - g[5] * g[6]) +
                       g[2] * (g[3] * g[7] - g[4] * g[6]);
    // A rotation by 72 degrees has trace 1 + 2 cos 72 = (1 + sqrt 5) / 2.
    const double tr_err = std::abs(Trace(g) - (1 + std::sqrt(5.0)) / 2);
    double worst_match = 0;
    for (int v = 0; v < NUM_VERTICES_MODEL; v++) {
      double gv[3] = {0, 0, 0};
      for (int i = 0; i < 3; i++)
        for (int k = 0; k < 3; k++) gv[i] += g[3 * i + k] * VERTICES_MODEL[v][k];
      double best = 1e300;
      for (int u = 0; u < NUM_VERTICES_MODEL; u++) {
        double d = 0;
        for (int i = 0; i < 3; i++) d = std::max(d, std::abs(gv[i] - VERTICES_MODEL[u][i]));
        best = std::min(best, d);
      }
      worst_match = std::max(worst_match, best);
    }
    const bool good = orth < 1e-11 && std::abs(det - 1) < 1e-11 && tr_err < 1e-11 && worst_match < 1e-9;
    printf("neighbor %2d: |GtG-I| %.1e  det-1 %.1e  trace err %.1e  vertex match %.1e  %s\n", n,
           orth, det - 1, tr_err, worst_match, good ? "ok" : "BAD");
    ok = ok && good;
  }
  // Closure: the group generated by the neighbors (within 1e-9).
  group->assign(1, Identity());
  for (size_t i = 0; i < group->size() && group->size() <= 200; i++) {
    for (int n = 0; n < NUM_SYMMETRY_NEIGHBORS; n++) {
      const M h = Mul((*group)[i], Neighbor(n));
      bool seen = false;
      for (const M &e : *group) seen = seen || MaxDiff(e, h) < 1e-9;
      if (!seen) group->push_back(h);
    }
  }
  printf("generated group: %zu elements (want 60)\n", group->size());
  return ok && group->size() == 60;
}

// Cayley coordinates of a rotation near the identity: R = cayley(w).
std::array<double, 3> CayleyOf(const M &r) {
  const double d = 1 + Trace(r);
  return {(r[7] - r[5]) / d, (r[2] - r[6]) / d, (r[3] - r[1]) / d};
}

bool CheckCell(const std::vector<M> &group, int samples) {
  std::mt19937_64 rng(1);
  double max_abs = 0, max_r2 = 0, worst_cayley = 0;
  int not_chart0 = 0, not_neighbor_cell = 0;
  for (int s = 0; s < samples; s++) {
    const M r0 = RandomRotation(rng);
    M best = r0;
    for (const M &g : group) {
      const M h = Mul(r0, g);
      if (Trace(h) > Trace(best)) best = h;
    }
    // Chart 0 is the chart of maximal trace(chart * R); charts 1..3 are the
    // diagonal half-turns.
    for (int c = 1; c <= 3; c++) {
      const M cm = FromYocto(geom5d::ChartMatrix(c));
      if (Trace(Mul(cm, best)) > Trace(best)) not_chart0++;
    }
    // The 12-neighbor cell contains the 60-element cell.
    for (int n = 0; n < NUM_SYMMETRY_NEIGHBORS; n++) {
      if (Trace(Mul(best, Neighbor(n))) > Trace(best) + 1e-12) not_neighbor_cell++;
    }
    const auto w = CayleyOf(best);
    const M back = FromYocto(geom5d::CayleyMatrix({w[0], w[1], w[2]}));
    worst_cayley = std::max(worst_cayley, MaxDiff(back, best));
    double r2 = 0;
    for (double x : w) {
      max_abs = std::max(max_abs, std::abs(x));
      r2 += x * x;
    }
    max_r2 = std::max(max_r2, r2);
  }
  printf("cell: %d samples; max |w_i| %.4f, max |w| %.4f (angle %.2f deg); Cayley round trip %.1e\n",
         samples, max_abs, std::sqrt(max_r2), 2 * std::atan(std::sqrt(max_r2)) * 180 / M_PI,
         worst_cayley);
  printf("cell: %d samples prefer another chart, %d violate the neighbor cell\n", not_chart0,
         not_neighbor_cell);
  return not_chart0 == 0 && not_neighbor_cell == 0 && worst_cayley < 1e-10;
}

bool CheckLeaves(const std::string &journals, int samples) {
  std::mt19937_64 rng(2);
  int64_t leaves = 0, points = 0, bad = 0;
  double min_adv = 1e300;
  for (int chart = 0; chart <= 2; chart++) {
    const std::string dir = journals + "/c" + std::to_string(chart);
    if (!std::filesystem::is_directory(dir)) continue;
    const geom5d::BoxQ root = geom5d::RootBox(chart);
    for (const auto &entry : std::filesystem::directory_iterator(dir)) {
      if (entry.path().extension() != ".journal") continue;
      const rows5d::Journal j = rows5d::ReadJournal(entry.path().string());
      for (const rows5d::Record &r : j.leaves) {
        const auto *pi = std::get_if<rows5d::IcoPruneLeaf>(&r.leaf);
        if (pi == nullptr) continue;
        leaves++;
        const geom5d::BoxD b = geom5d::ToDouble(rows5d::NodeBox(root, r.path));
        const M g = Neighbor(pi->neighbor);
        for (int s = 0; s < samples; s++) {
          geom5d::vec3 w;
          for (int a = 0; a < 3; a++) {
            // Corners first, then uniform points.
            const double t = s < 8 ? ((s >> a) & 1 ? 1.0 : -1.0)
                                   : std::uniform_real_distribution<double>(-1, 1)(rng);
            w[a] = b.center[a] + t * b.radius[a];
          }
          if (w[0] * w[0] + w[1] * w[1] + w[2] * w[2] > 3) continue;
          points++;
          const M rel = FromYocto(geom5d::RelativeRotation(chart, w));
          const double adv = Trace(Mul(rel, g)) - Trace(rel);
          min_adv = std::min(min_adv, adv);
          if (adv <= 0) {
            if (bad < 10) {
              printf("BAD: %s c%d path %s n %d at (%g, %g, %g): advantage %g\n",
                     entry.path().filename().c_str(), chart, r.path.c_str(), pi->neighbor, w[0], w[1],
                     w[2], adv);
            }
            bad++;
          }
        }
      }
    }
  }
  printf("leaves: %lld pi leaves, %lld points in the Cayley ball, min advantage %.3e, %lld bad\n",
         (long long)leaves, (long long)points, leaves ? min_adv : 0.0, (long long)bad);
  return bad == 0;
}

}  // namespace

int main(int argc, char **argv) {
  std::string journals = "jobs";
  int samples = 64, cell_samples = 1000000;
  for (int i = 1; i < argc; i++) {
    const std::string a = argv[i];
    auto next = [&]() -> std::string {
      CHECK(i + 1 < argc) << a << " needs a value";
      return argv[++i];
    };
    if (a == "--journals") journals = next();
    else if (a == "--samples") samples = std::stoi(next());
    else if (a == "--cell_samples") cell_samples = std::stoi(next());
    else LOG(FATAL) << "unknown argument " << a;
  }
  std::vector<M> group;
  const bool n_ok = CheckNeighbors(&group);
  const bool c_ok = n_ok && CheckCell(group, cell_samples);
  const bool l_ok = CheckLeaves(journals, samples);
  printf("%s\n", n_ok && c_ok && l_ok ? "OK" : "FAILED");
  return n_ok && c_ok && l_ok ? 0 : 1;
}
