#!/usr/bin/env python3
# Exact model of the snub dodecahedron for the C5 pipeline (codebdd
# --model_file), in a frame with a 5-fold axis (through two pentagons) on z
# and a 2-fold axis on x.
#
# The snub dodecahedron is the orbit of one vertex under the icosahedral
# rotation group I (60 rotations). We take cc-lib's vertex (geom/polyhedra.cc,
# TwoEdgeLengthSnubDodecahedron: xi is the real root of xi^3 - 2 xi = phi ...
# in its closed form) to 80 digits, generate I exactly (to 80 digits) in the
# standard frame, check that the orbit has 60 points and that every edge has
# the same length, rotate to the 5-fold frame, and split the vertices into
# 12 C5 orbits: vertex i = 12 k + s is Rz(2 pi k / 5) applied to seed s
# (seeds sorted by decreasing z).
#
# Output (snub_model.txt):
#   name snubdodecahedron
#   seeds 12
#   vertex i x y z           60 lines, unit circumradius, 40 decimals
#   face i j k ...           the non-triangular faces (pentagons)
#   neighbor m00 m01 ... m22 the 12 rotations by +-72 degrees about the six
#                            5-fold axes (the Dirichlet-cell neighbors of the
#                            identity in SO(3)/I), row-major, 40 decimals
#   view_triangle a b c ...  the view domain: a rational triangle on the plane
#                            x + y + z = 1 (3 corners, 9 fractions) containing
#                            the Schwarz chamber of Ih at the z pole
#
# Usage: python3 ../common/snub_model.py [out=snub_model.txt] [header=symmetry_neighbors.h]

import itertools
import sys
from decimal import Decimal as D, getcontext

getcontext().prec = 90
TOL = D(10) ** -60

def sqrt(x): return x.sqrt()
def cbrt(x):
    if x < 0: return -cbrt(-x)
    y = D(float(x) ** (1 / 3))
    for _ in range(200):
        y = y - (y * y * y - x) / (3 * y * y)
    return y

phi = (1 + sqrt(D(5))) / 2
term = sqrt(phi - D(5) / 27)
xi = cbrt((phi + term) / 2) + cbrt((phi - term) / 2)

# cc-lib's first vertex (odd number of negative signs: s3 = -1).
p = [phi * sqrt(phi * (xi - 1 - 1 / xi)),
     xi * phi * sqrt(3 - xi * xi),
     -phi * sqrt(xi * (xi + phi) + 1)]

def matmul(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]
def apply(m, v):
    return [sum(m[i][k] * v[k] for k in range(3)) for i in range(3)]
def close(a, b, tol=TOL):
    return all(abs(x - y) < tol for x, y in zip(a, b))
def flat(m): return [x for row in m for x in row]
def dot(a, b): return sum(x * y for x, y in zip(a, b))
def cross(a, b): return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]
def norm(a): return sqrt(dot(a, a))

# Icosahedral rotation group in the standard frame (icosahedron vertices
# (0, +-phi, +-1) cyclically): generated by the cyclic permutation and a
# 5-fold rotation.
one, zero, half = D(1), D(0), D(1) / 2
cyc = [[zero, one, zero], [zero, zero, one], [one, zero, zero]]
five = [[half, -phi / 2, 1 / (2 * phi)],
        [phi / 2, 1 / (2 * phi), -half],
        [1 / (2 * phi), half, phi / 2]]
ident = [[one, zero, zero], [zero, one, zero], [zero, zero, one]]
group = [ident]
frontier = [ident]
while frontier:
    nxt = []
    for g in frontier:
        for h in (cyc, five):
            m = matmul(g, h)
            if not any(close(flat(m), flat(x)) for x in group):
                group.append(m)
                nxt.append(m)
    frontier = nxt
assert len(group) == 60, len(group)
ico = [v for c in itertools.product((1, -1), repeat=2) for v in
       ([zero, c[0] * phi, c[1] * one], [c[0] * phi, c[1] * one, zero], [c[1] * one, zero, c[0] * phi])]
for g in group:  # every element preserves the icosahedron
    for v in ico:
        assert any(close(apply(g, v), w) for w in ico)

verts = []
for g in group:
    v = apply(g, p)
    if not any(close(v, w) for w in verts):
        verts.append(v)
assert len(verts) == 60
r = norm(p)
verts = [[x / r for x in v] for v in verts]

# Hull faces (exact up to 1e-60): supporting planes through vertex triples.
n = len(verts)
faces = []
for i, j, k in itertools.combinations(range(n), 3):
    nv = cross([a - b for a, b in zip(verts[j], verts[i])], [a - b for a, b in zip(verts[k], verts[i])])
    if norm(nv) < TOL: continue
    d = dot(nv, verts[i])
    vals = [dot(nv, v) - d for v in verts]
    if any(x > TOL for x in vals) and any(x < -TOL for x in vals): continue
    face = tuple(m for m in range(n) if abs(vals[m]) < TOL)
    if face not in faces: faces.append(face)
counts = {}
for f in faces: counts[len(f)] = counts.get(len(f), 0) + 1
assert counts == {3: 80, 5: 12}, counts
# Every edge (pair of vertices sharing two faces) has the same length.
edges = set()
for f in faces:
    for a, b in itertools.combinations(f, 2):
        if sum(1 for g in faces if a in g and b in g) == 2: edges.add((a, b))
assert len(edges) == 150, len(edges)
lengths = [norm([x - y for x, y in zip(verts[a], verts[b])]) for a, b in edges]
assert max(lengths) - min(lengths) < TOL, (min(lengths), max(lengths))

# 5-fold frame: z along the axis through a pentagon (the pentagon's centroid
# direction), x along a 2-fold axis perpendicular to it.
pent = [f for f in faces if len(f) == 5][0]
axis = [sum(verts[m][c] for m in pent) for c in range(3)]
axis = [x / norm(axis) for x in axis]
def rotation_axis(g):
    # Axis of a rotation by pi: the +1 eigenvector, from g + I (rank 1).
    m = [[g[i][j] + (one if i == j else zero) for j in range(3)] for i in range(3)]
    col = max(range(3), key=lambda j: sum(m[i][j] ** 2 for i in range(3)))
    v = [m[i][col] for i in range(3)]
    return [x / norm(v) for x in v]
trace = lambda g: g[0][0] + g[1][1] + g[2][2]
two_fold = [rotation_axis(g) for g in group if abs(trace(g) + 1) < TOL]
e1 = next(a for a in two_fold if abs(dot(a, axis)) < TOL)
e3 = axis
e2 = cross(e3, e1)
frame = [e1, e2, e3]
fv = [apply(frame, v) for v in verts]
fgroup = [matmul(matmul(frame, g), [list(r) for r in zip(*frame)]) for g in group]

# C5 orbits: Rz(72 k). Seeds: azimuth in [0, 72) degrees, sorted by z.
c72 = (phi - 1) / 2
s72 = sqrt(1 - c72 * c72)
def rz(k, v):
    c, s = one, zero
    for _ in range(k % 5):
        c, s = c * c72 - s * s72, s * c72 + c * s72
    return [c * v[0] - s * v[1], s * v[0] + c * v[1], v[2]]
rz72 = [[c72, -s72, zero], [s72, c72, zero], [zero, zero, one]]
assert any(close(flat(g), flat(rz72)) for g in fgroup)
import math
def azimuth(v): return math.atan2(float(v[1]), float(v[0])) % (2 * math.pi)
seeds = [v for v in fv if azimuth(v) < 2 * math.pi / 5 - 1e-12]
assert len(seeds) == 12
seeds.sort(key=lambda v: (-v[2], azimuth(v)))
model = [rz(k, s) for k in range(5) for s in seeds]
index = {}
for i, v in enumerate(model):
    j = next(j for j, w in enumerate(fv) if close(v, w))
    index[j] = i
assert len(index) == 60
mfaces = [sorted(index[m] for m in f) for f in faces]

neighbors = [g for g in fgroup if abs(trace(g) - phi) < TOL]  # angle 72: trace 1 + 2 cos 72 = phi
assert len(neighbors) == 12

# View domain: the Schwarz (2,3,5) chamber of Ih = I x {+-1} at the z pole
# between the mirrors at azimuths 18 and 54 degrees. Its corners are z, the
# 3-fold axis at azimuth 18 (polar 37.38 degrees) and the 2-fold axis at
# azimuth 54 (polar 31.72 degrees); its third side is on the bisector of z
# and the 5-fold axis at azimuth 54. VIEW_TRIANGLE is a rational triangle on
# the plane x + y + z = 1 containing it, bounded by y >= (8/25) x (tan 18 =
# 0.3249), y <= (69/50) x (tan 54 = 1.3764), and 1.95 x + 2.3 y <= 1 (the
# bisector is 1.95106 x + 2.30902 y <= 1); every exact corner is checked to
# be inside, so the chamber (their convex hull) is.
def axis_of(g):
    v = [g[2][1] - g[1][2], g[0][2] - g[2][0], g[1][0] - g[0][1]]
    if norm(v) < TOL:  # rotation by pi: from g + I
        return rotation_axis(g)
    return [x / norm(v) for x in v]
def azimuth_deg(v): return math.degrees(math.atan2(float(v[1]), float(v[0]))) % 360
def find_axis(tr, az):
    for g in fgroup:
        if abs(trace(g) - tr) < TOL:
            for sgn in (1, -1):
                v = [sgn * x for x in axis_of(g)]
                if v[2] > 0 and abs(azimuth_deg(v) - az) < 1e-6 and float(v[2]) > 0.7:
                    return v
    raise AssertionError((tr, az))
corner3 = find_axis(zero, 18)        # 3-fold: trace 1 + 2 cos 120 = 0
corner2 = find_axis(-one, 54)        # 2-fold: trace -1
chamber = [[zero, zero, one], corner3, corner2]
from fractions import Fraction as F
VIEW_TRIANGLE = [(F(0), F(0), F(1)), (F(500, 1343), F(160, 1343), F(683, 1343)),
                 (F(250, 1281), F(345, 1281), F(686, 1281))]
for c in VIEW_TRIANGLE: assert sum(c) == 1
def proj(v):
    t = sum(v)
    return [x / t for x in v]
def in_triangle(p, tri):  # barycentric coordinates, all > 0 (strict)
    a, b, c = [[D(x.numerator) / D(x.denominator) for x in t] for t in tri]
    def det2(u, v, w): return (u[0] - w[0]) * (v[1] - w[1]) - (v[0] - w[0]) * (u[1] - w[1])
    total = det2(a, b, c)
    l = [det2(p, b, c) / total, det2(a, p, c) / total, det2(a, b, p) / total]
    return min(l)
for k, cnr in enumerate(chamber):
    m = in_triangle(proj(cnr), VIEW_TRIANGLE)
    assert m > 0 or (k == 0 and abs(m) < TOL), (k, m)  # the pole is a shared corner

out = sys.argv[1] if len(sys.argv) > 1 else "snub_model.txt"
fmt = lambda x: f"{x:.40f}"
with open(out, "w") as f:
    f.write("name snubdodecahedron\nseeds 12\n")
    for i, v in enumerate(model):
        f.write(f"vertex {i} {' '.join(fmt(x) for x in v)}\n")
    for fc in mfaces:
        if len(fc) > 3: f.write("face " + " ".join(map(str, fc)) + "\n")
    for g in neighbors:
        f.write("neighbor " + " ".join(fmt(x) for x in flat(g)) + "\n")
    f.write("view_triangle " + " ".join(f"{x.numerator}/{x.denominator}" for c in VIEW_TRIANGLE for x in c) + "\n")
# The neighbors rounded to 10^-12 (|exact - rational| < 10^-12 per entry), for
# the search's icosahedral prune (exact5d IcoPrune*) and, identically, Lean.
hdr = sys.argv[2] if len(sys.argv) > 2 else "symmetry_neighbors.h"
scale = 10 ** 12
with open(hdr, "w") as f:
    f.write("// Generated by snub_model.py: the 12 rotations by +-72 degrees about the\n"
            "// six 5-fold axes of the snub dodecahedron (5-fold frame), each entry\n"
            "// rounded to a multiple of 10^-12 (error < 10^-12). The icosahedral\n"
            "// prune (exact5d::IcoPruneValid) uses them.\n"
            "#ifndef _NOPERT_SYMMETRY_NEIGHBORS_H\n#define _NOPERT_SYMMETRY_NEIGHBORS_H\n\n"
            "#include <cstdint>\n\n"
            f"inline constexpr int NUM_SYMMETRY_NEIGHBORS = {len(neighbors)};\n"
            f"inline constexpr int64_t SYMMETRY_NEIGHBOR_DENOM = {scale};\n"
            "// Row-major numerators.\n"
            "inline constexpr int64_t SYMMETRY_NEIGHBOR_NUM[NUM_SYMMETRY_NEIGHBORS][9] = {\n")
    for g in neighbors:
        nums = [int((x * scale).to_integral_value()) for x in flat(g)]
        for x, q in zip(flat(g), nums):
            assert abs(x * scale - q) <= D(1) / 2
        f.write("  {" + ", ".join(str(q) for q in nums) + "},\n")
    f.write("};\n\n#endif\n")
print(f"wrote {hdr}")
print(f"wrote {out}: 60 vertices (12 seeds), {counts[5]} pentagons, {counts[3]} triangles, "
      f"edge length {float(lengths[0]):.15f}, xi = {float(xi):.15f}")
print("seed z:", " ".join(f"{float(s[2]):+.4f}" for s in seeds))
