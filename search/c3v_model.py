#!/usr/bin/env python3
"""Exact rational C3v model of a 7-vertex candidate (the Septopert).

Puts the 3-fold axis along (1,1,1), where C3v acts by permuting coordinates,
so that a rational model is exactly C3v-symmetric. The input (an .xyz file,
axis z, mirror planes at azimuths that are multiples of 60 degrees) is mapped
with e1 = (-1,-1,2)/sqrt6 (azimuth 0), e2 = (1,-1,0)/sqrt2, e3 = (1,1,1)/sqrt3;
a vertex on the mirror x = y becomes (a, a, b), one on the axis (t, t, t).
Each such parameter is rounded to a multiple of 1/DEN, and the orbit is
generated exactly. Checks: 7 distinct vertices, all extreme, triangular faces
(none coplanar with a fourth vertex), C3v invariance, the face list.

The input is scaled to circumradius SCALE = 1 - 1e-6 first (the proof
infrastructure needs every vertex strictly inside the unit ball).
With a third argument, also writes the Lean data module there
(`Noperthedron.Septopert.ModelData`: the vertices and, for each of c3Mat k
and mirrorMat i, the vertex permutation it induces).

Usage: python3 c3v_model.py candidate.xyz [den=2^20 [ModelData.lean]] > model.txt
"""
import itertools, math, sys
from fractions import Fraction as F

path = sys.argv[1]
den = int(sys.argv[2]) if len(sys.argv) > 2 else 1 << 20
pts = [list(map(float, l.split())) for l in open(path) if l.strip() and not l.startswith('#')]
SCALE = 1 - 1e-6
rad = max(math.sqrt(sum(c * c for c in p)) for p in pts)
pts = [[c * SCALE / rad for c in p] for p in pts]
s2, s3, s6 = math.sqrt(2), math.sqrt(3), math.sqrt(6)
e1, e2, e3 = (-1 / s6, -1 / s6, 2 / s6), (1 / s2, -1 / s2, 0), (1 / s3, 1 / s3, 1 / s3)
def rnd(x): return F(round(x * den), den)

seen, verts = set(), []
def add(v):
  if v not in seen: seen.add(v); verts.append(v)
for x, y, z in pts:
  w = [x * e1[i] + y * e2[i] + z * e3[i] for i in range(3)]
  # nearest representative of the form (a,a,b) up to permutation, or (t,t,t)
  if max(w) - min(w) < 1e-9:
    t = rnd(sum(w) / 3); orbit = [(t, t, t)]
  else:
    best = None
    for i, j, k in itertools.permutations(range(3)):
      if i < j:
        err = abs(w[i] - w[j])
        if best is None or err < best[0]: best = (err, i, j, k)
    err, i, j, k = best
    assert err < 1e-9, (w, err)
    a, b = rnd((w[i] + w[j]) / 2), rnd(w[k])
    orbit = [(b, a, a), (a, b, a), (a, a, b)]
  for v in orbit: add(v)
assert len(verts) == 7, len(verts)
# C3v invariance (exact)
S = set(verts)
for p in itertools.permutations(range(3)):
  assert {tuple(v[p[i]] for i in range(3)) for v in verts} == S

def sub(a, b): return [x - y for x, y in zip(a, b)]
def cross(a, b): return [a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0]]
def dot(a, b): return sum(x * y for x, y in zip(a, b))
faces = []
for i, j, k in itertools.combinations(range(7), 3):
  n = cross(sub(verts[j], verts[i]), sub(verts[k], verts[i]))
  d = [dot(n, sub(verts[l], verts[i])) for l in range(7) if l not in (i, j, k)]
  assert any(d), "degenerate"
  if all(x <= 0 for x in d) or all(x >= 0 for x in d):
    assert all(x != 0 for x in d), ("coplanar face", i, j, k)
    if all(x > 0 for x in d): j, k = k, j       # outward orientation
    faces.append((i, j, k))
deg = [sum(v in f for f in faces) for v in range(7)]
assert len(faces) == 10 and sorted(deg) == [3, 4, 4, 4, 5, 5, 5], (len(faces), deg)
r2 = max(dot(v, v) for v in verts)
print("name", path.split('/')[-1].rsplit('.', 1)[0])
print("# axis (1,1,1); C3v = coordinate permutations; denominators", den)
print("# max |v| = %.12f; degrees %s" % (math.sqrt(r2), deg))
for i, v in enumerate(verts):
  print("vertex %d %s" % (i, " ".join("%.20f" % float(c) for c in v)))
for i, v in enumerate(verts):
  print("rational_vertex %d %s" % (i, " ".join(str(c) for c in v)))
for f in faces: print("face", *f)
# The view domain D' = {u0 >= u1 >= 0, u1 >= u2} (Lean: Septopert.InC3vViewDomain),
# the cone over (1,1,1), (1,0,0), (0,0,-1), as two triangles split by u2 = 0:
# T1 = (1,1,1), (1,1,0), (1,0,0) in projective root 0 (on u0 + u1 + u2 = 1) and
# T2 = (1,0,0), (1,1,0), (0,0,-1) in root 1 (on u0 + u1 - u2 = 1); codebdd.
print("view_triangle 1/3 1/3 1/3 1/2 1/2 0 1 0 0")
print("view_triangle 1 0 0 1/2 1/2 0 0 0 -1")
assert r2 < 1
if len(sys.argv) > 3:
  def perm_of(f):
    return [verts.index(f(v)) for v in verts]
  c3 = [lambda v: v, lambda v: (v[1], v[2], v[0]), lambda v: (v[2], v[0], v[1])]
  mir = [lambda v: (v[0], v[2], v[1]), lambda v: (v[2], v[1], v[0]), lambda v: (v[1], v[0], v[2])]
  def fin7(l): return "![" + ", ".join(map(str, l)) + "]"
  def q(c): return "(%d / %d : ℚ)" % (c.numerator, c.denominator) if c.denominator != 1 else "(%d : ℚ)" % c.numerator
  with open(sys.argv[3], 'w') as f:
    f.write("""module

public import Mathlib

@[expose] public section

/-!
# The rational model of the 7-vertex candidate (generated by c3v_model.py)

%s, axis (1,1,1): vertices (a,a,b) up to coordinate permutation and (t,t,t),
denominators %d. `c3Perm k` and `mirrorPerm i` are the vertex permutations
induced by `c3Mat k` and `mirrorMat i` (coordinate permutations).
-/

namespace Noperthedron.Septopert

def vertexQ : Fin 7 → Fin 3 → ℚ := ![
%s]

def c3Perm : Fin 3 → Fin 7 → Fin 7 := ![%s]

def mirrorPerm : Fin 3 → Fin 7 → Fin 7 := ![%s]

end Noperthedron.Septopert
""" % (path.split('/')[-1], den,
       ",\n".join("  ![%s]" % ", ".join(q(c) for c in v) for v in verts),
       ", ".join(fin7(perm_of(g)) for g in c3),
       ", ".join(fin7(perm_of(g)) for g in mir)))
