#!/usr/bin/env python3
"""Generate proof/DeltoidalHexecontahedron/TieData.lean: the deltoidal hexecontahedron's
tie-tube data for Lean.

- The pinning normals x_n (dh_tie_data.txt `X` lines, exact over K), the exact
  half-turns H_n = 2 x xᵀ / |x|² − I over K, and their rounded numerators
  (tie_normals.h: H rounded to multiples of 10^-12), which the 5D search's tie
  rows use (exact5d::TieLeafValid). Lean checks H_n (x·x) = 2 x xᵀ − (x·x) I
  and the rounding.
- With --export DIR (tietube.cc --export output): the tie nodes the 5D search
  may cite, i.e. every node of a tie tree whose whole subtree is certified
  (rho > 0): normal, view triangle, rho, and children (split nodes). Leaves
  are proved by their certificates (checked natively from DIR); split nodes
  follow from their children. Also writes DIR/nodes.txt ("<n> <t> <path>
  <index>") for pack5d's tag-15 rows.

Usage: python3 dh_tie_lean.py [--export DIR] [--out FILE]
"""

import argparse
import os
import re
from fractions import Fraction as F
from pathlib import Path

from kfield import K, dot

ap = argparse.ArgumentParser()
ap.add_argument("--data", default="dh_tie_data.txt")
ap.add_argument("--header", default="tie_normals.h")
ap.add_argument("--export", default=None)
ap.add_argument("--out", default=str(Path(os.environ.get("NOPERTS_PROOF", "../../proof")) /
                                     "DeltoidalHexecontahedron/TieData.lean"))
args = ap.parse_args()

X = {}
for line in open(args.data):
    t = line.split()
    if t and t[0] == "X":
        X[int(t[1])] = [K.parse(t[2 + 4 * k: 6 + 4 * k]) for k in range(3)]
N = len(X)
hdr = open(args.header).read()
body = hdr[hdr.index("TIE_HALF_TURN_NUM"):]
nums = [[int(v) for v in re.findall(r"-?\d+", row)] for row in re.findall(r"\{([-\d, ]+)\}", body)]
assert len(nums) == N and all(len(r) == 9 for r in nums), (len(nums), N)


def q(x):
    return f"({x.numerator} : ℚ)" if x.denominator == 1 else f"({x.numerator} / {x.denominator} : ℚ)"


def kq(k):
    return "⟨" + ", ".join(q(v) for v in k.v) + "⟩"


def kvec(v):
    return "![" + ", ".join(kq(c) for c in v) + "]"


H = []
for n in range(N):
    x = X[n]
    xx = dot(x, x)
    H.append([[x[i] * x[j] * 2 / xx - (K(1) if i == j else K()) for j in range(3)] for i in range(3)])
    for i in range(3):
        for j in range(3):
            assert abs(H[n][i][j].f() - nums[n][3 * i + j] / 1e12) < 1e-12

# Tie nodes from the export.
nodes = []  # (normal, triangle, rho, kids)
index_lines = []
if args.export:
    for fn in sorted(os.listdir(args.export)):
        m = re.match(r"n(\d+)_t(\d+)\.cert$", fn)
        if not m:
            continue
        n, t = int(m.group(1)), int(m.group(2))
        rows = {}
        for line in open(os.path.join(args.export, fn)):
            tok = line.split()
            if not tok or tok[0] != "node":
                continue
            # node <path> <kind S|L|X> <rho> <9 corner rationals>
            path = "" if tok[1] == "." else tok[1]
            rows[path] = (tok[2], F(tok[3]), [F(v) for v in tok[4:13]])
        # rho_min over subtrees; keep nodes whose subtree is fully certified.
        memo = {}

        def rmin(p):
            if p in memo:
                return memo[p]
            kind, rho, _ = rows[p]
            if kind == "L":
                r = rho
            elif kind == "S":
                r = min(rmin(p + str(c)) for c in range(4))
            else:
                r = F(0)
            memo[p] = r
            return r

        def emit(p):
            kind, rho, tri = rows[p]
            k = len(nodes)
            nodes.append(None)
            kids = [emit(p + str(c)) for c in range(4)] if kind == "S" else []
            nodes[k] = (n, tri, rmin(p), kids)
            index_lines.append(f"{n} {t} {p if p else '.'} {k}")
            return k

        def walk(p):
            if p not in rows:
                return
            if rmin(p) > 0:
                emit(p)
            elif rows[p][0] == "S":
                for c in range(4):
                    walk(p + str(c))

        walk("")
    with open(os.path.join(args.export, "nodes.txt"), "w") as f:
        f.write("\n".join(index_lines) + "\n")

out = []
w = out.append
w("module\n\npublic import DeltoidalHexecontahedron.TieCheck\n\n@[expose] public section\n")
w("/-!\n# The deltoidal hexecontahedron's tie tubes (generated by `search/dh/dh_tie_lean.py`)\n\n"
  "The pinning normals (exact x, exact half-turn H, and H rounded to 10⁻¹² as the\n"
  "5D search uses it) and the tie nodes the search's tie rows cite.\n-/\n")
w("open Noperts Noperts.Pipeline\n")
w("namespace DeltoidalHexecontahedron.Tie\n")
w("/-- The pinning normals x_n. -/")
w("def dhTieX : Array KVec := #[\n" + ",\n".join("  " + kvec(X[n]) for n in range(N)) + "]\n")
w("/-- The exact half-turns H_n (rows). -/")
w("def dhTieH : Array (Fin 3 → KVec) := #[\n" +
  ",\n".join("  ![" + ", ".join(kvec(H[n][i]) for i in range(3)) + "]" for n in range(N)) + "]\n")
w("/-- H_n rounded: row-major numerators over 10^12 (tie_normals.h). -/")
w("def dhTieNum : Array (List Int) := #[\n" + ",\n".join("  [" + ", ".join(map(str, r)) + "]" for r in nums) + "]\n")
w("/-- The tie nodes: normal, view triangle (corners), certified radius, children (split nodes). -/")
w("def dhTieNodes : Array TieNode := #[" + ("\n" if nodes else "") + ",\n".join(
    f"  ⟨{n}, ![" + ", ".join("![" + ", ".join(q(v) for v in tri[3 * c:3 * c + 3]) + "]" for c in range(3)) +
    f"], {q(rho)}, [{', '.join(map(str, kids))}]⟩" for n, tri, rho, kids in nodes) + "]\n")
w("end DeltoidalHexecontahedron.Tie")
Path(args.out).write_text("\n".join(out) + "\n")
print(f"wrote {args.out}: {N} normals, {len(nodes)} tie nodes")
