#!/usr/bin/env python3
"""ico-group.h: the 60 rotations of the icosahedral group I in the 5-fold
frame (z a 5-fold axis, x a 2-fold axis; the snub/PH/DH models' frame), each
entry rounded to the nearest multiple of 10^-12 (error <= 5 * 10^-13).

The order is Noperthedron's IcoGroupData.icoEntry (BFS from the identity over
the generators Rz(72), Rx(180) and the tilted 72-degree rotation, as in
Noperthedron/scripts/snub-ico-group.py), so index n here is icoEntry n there.
Used by the half-turn prune (exact5d::HalfTurnPruneValid).

Usage: python3 ico-group.py [out=ico-group.h] [lean_out=../../proof/DeltoidalHexecontahedron/IcoGroupRounded.lean]
"""

import sys
from decimal import Decimal as D, getcontext
from fractions import Fraction as F

getcontext().prec = 60
R5 = D(5).sqrt()
S72 = ((5 + R5) / 8).sqrt()


class K:
    """a + b sqrt5 + c s + d s sqrt5, s^2 = (5 + sqrt5)/8."""

    __slots__ = ("v",)

    def __init__(self, a=0, b=0, c=0, d=0):
        self.v = (F(a), F(b), F(c), F(d))

    def __add__(x, y):
        return K(*(p + q for p, q in zip(x.v, y.v)))

    def __neg__(x):
        return K(*(-p for p in x.v))

    def __sub__(x, y):
        return x + (-y)

    def __mul__(x, y):
        a, b, c, d = x.v
        e, f, g, h = y.v
        p, q = c * g + 5 * d * h, c * h + d * g
        return K(a * e + 5 * b * f + (5 * p + 5 * q) / 8, a * f + b * e + (p + 5 * q) / 8,
                 a * g + 5 * b * h + c * e + 5 * d * f, a * h + b * g + c * f + d * e)

    def __eq__(x, y):
        return x.v == y.v

    def __hash__(x):
        return hash(x.v)

    def dec(x):
        a, b, c, d = (D(q.numerator) / D(q.denominator) for q in x.v)
        return a + b * R5 + c * S72 + d * R5 * S72


Z, ONE = K(), K(1)
IDENTITY = tuple(tuple(ONE if i == j else Z for j in range(3)) for i in range(3))
C72 = K(F(-1, 4), F(1, 4))
S72K = K(0, 0, 1)
RZ = ((C72, -S72K, Z), (S72K, C72, Z), (Z, Z, ONE))
RX = ((ONE, Z, Z), (Z, -ONE, Z), (Z, Z, -ONE))


def mm(x, y):
    return tuple(tuple(sum((x[i][k] * y[k][j] for k in range(3)), Z) for j in range(3)) for i in range(3))


def tilted_rotation():
    sin_t, cos_t = K(0, F(2, 5)), K(0, F(1, 5))
    cos_a = K(0, 0, F(-1, 2), F(1, 2))
    sin_a = K(F(1, 4), F(1, 4))
    n = (sin_t * cos_a, sin_t * sin_a, cos_t)
    cross = ((Z, -n[2], n[1]), (n[2], Z, -n[0]), (-n[1], n[0], Z))
    return tuple(tuple((C72 if i == j else Z) + S72K * cross[i][j] + (ONE - C72) * n[i] * n[j]
                       for j in range(3)) for i in range(3))


gens = [RZ, RX, tilted_rotation()]
group, index = [IDENTITY], {IDENTITY: 0}
i = 0
while i < len(group):
    for g in gens:
        h = mm(group[i], g)
        if h not in index:
            index[h] = len(group)
            group.append(h)
    i += 1
assert len(group) == 60
SCALE = 10 ** 12
rows = []
for g in group:
    nums = [int((g[i][j].dec() * SCALE).to_integral_value()) for i in range(3) for j in range(3)]
    for i in range(3):
        for j in range(3):
            assert abs(D(nums[3 * i + j]) / SCALE - g[i][j].dec()) <= D(5) / 10 ** 13
    rows.append(nums)
# Half-turns: trace -1.
half = [n for n, g in enumerate(group) if sum((g[i][i] for i in range(3)), Z) == K(-1)]
assert len(half) == 15

out = sys.argv[1] if len(sys.argv) > 1 else "ico-group.h"
with open(out, "w") as f:
    f.write("// Generated by ico-group.py: the 60 rotations of the icosahedral group in\n"
            "// the 5-fold frame, in Noperthedron's icoEntry order, each entry rounded to\n"
            "// the nearest multiple of 10^-12 (error <= 5 * 10^-13). Used by the\n"
            "// half-turn prune (exact5d::HalfTurnPruneValid).\n")
    f.write("#ifndef _NOPERT_ICO_GROUP_H\n#define _NOPERT_ICO_GROUP_H\n\n#include <cstdint>\n\n")
    f.write("inline constexpr int ICO_GROUP_SIZE = 60;\n")
    f.write(f"inline constexpr int64_t ICO_GROUP_DENOM = {SCALE};\n")
    f.write("// Row-major numerators.\ninline constexpr int64_t ICO_GROUP_NUM[ICO_GROUP_SIZE][9] = {\n")
    for r in rows:
        f.write("  {" + ", ".join(str(x) for x in r) + "},\n")
    f.write("};\n")
    f.write("// The 15 half-turns (trace -1).\ninline constexpr int ICO_HALF_TURNS[15] = {" +
            ", ".join(str(n) for n in half) + "};\n\n#endif\n")
lean_out = sys.argv[2] if len(sys.argv) > 2 else "../../proof/DeltoidalHexecontahedron/IcoGroupRounded.lean"
lines = ["module", "", "@[expose] public section", "", "/-!",
         "# The icosahedral group, rounded (generated by `search/dh/ico-group.py`)", "",
         "The 60 rotations of `icoEntry`, each entry rounded to the nearest multiple of",
         "10⁻¹² (`exact5d::HalfTurnPruneValid` in the C++ search uses these numerators);",
         "`AtlasHalfTurnPrune.groupCheck` bounds the rounding by 5 · 10⁻¹³.", "-/", "",
         "namespace DeltoidalHexecontahedron", "",
         "/-- Row-major numerators over 10¹² (icoEntry order). -/", "def icoGroupNum : List (List Int) := ["]
for k, r in enumerate(rows):
    lines.append("  [" + ", ".join(str(x) for x in r) + "]" + ("," if k < 59 else ""))
lines += ["]", "", "/-- The 15 half-turns (trace −1). -/",
          "def icoHalfTurns : List Nat := [" + ", ".join(map(str, half)) + "]", "",
          "end DeltoidalHexecontahedron", ""]
with open(lean_out, "w") as f:
    f.write("\n".join(lines))
print(f"wrote {out} and {lean_out}: 60 rotations, half-turns {half}")
