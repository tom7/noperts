"""Install new exact rational vertices into proof/DeltoidalHexecontahedron/SolidModel.lean.

Reads the rational vertex list exported by the C++ tool codebdd
(model_vertices.lean, by default next to this repository) and rewrites
the bodies of `slotVertices` (all N = 5 S rows) and `seedVertices` (the
first S rows, i.e. orbit 0) in SolidModel.lean, and the sizes N and S wherever
SolidModel.lean spells them as `Fin N`, `Fin S`, `icoOrbitsCheck S` and
`seedCount := S`. (The N and S in its descriptive prose are not touched.)
Vertex order is rotation-major (index = S * orbit + seed), as generated by
codebdd.

After this, rebuild.
"""

from __future__ import annotations

import argparse
import os
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
# The Lean project: proof/ of this repository (this script is in search/dh/scripts).
REPO = HERE.parents[2] / "proof"


def read_rows(exported: Path) -> list[str]:
    text = exported.read_text(encoding="utf-8")
    m = re.search(r"def rationalVertices : VertexIndex → Fin 3 → ℚ := !\[\n(.*?)\n\]", text, re.S)
    if not m:
        raise SystemExit(f"{exported}: no rationalVertices definition found")
    rows = [line.strip().rstrip(",") for line in m.group(1).splitlines() if line.strip()]
    if len(rows) % 5 != 0 or not all(r.startswith("![") and r.endswith("]") for r in rows):
        raise SystemExit(f"{exported}: expected 5 * seeds rows, got {len(rows)}")
    return rows


def replace_def(text: str, header: str, rows: list[str]) -> str:
    pattern = re.compile(re.escape(header) + r"\n.*?\n\]", re.S)
    body = header + "\n" + ",\n".join("  " + r for r in rows) + "\n]"
    new, n = pattern.subn(lambda _: body, text, count=1)
    if n != 1:
        raise SystemExit(f"could not find `{header}` in SolidModel.lean")
    return new


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--exported", type=Path, default=None,
                        help="codebdd's model_vertices.lean (default: $MODEL_DIR/model_vertices.lean)")
    parser.add_argument("--solid_model", type=Path,
                        default=REPO / "DeltoidalHexecontahedron" / "SolidModel.lean")
    args = parser.parse_args()
    if args.exported is None:
        if not os.environ.get("MODEL_DIR"):
            raise SystemExit("pass --exported or set MODEL_DIR to the C++ pipeline directory")
        args.exported = Path(os.environ["MODEL_DIR"]) / "model_vertices.lean"
    rows = read_rows(args.exported)
    text = args.solid_model.read_text(encoding="utf-8")
    n, seeds = len(rows), len(rows) // 5
    # The slot count N = 5 * seeds and the seed count, wherever SolidModel.lean spells them.
    for pattern, repl, count in [
            (r"def slotVertices : Fin \d+ →", f"def slotVertices : Fin {n} →", 1),
            (r"fun i : Fin \d+ => Array\.ofFn", f"fun i : Fin {n} => Array.ofFn", 1),
            (r"def slotVerticesImpl \(i : Fin \d+\)", f"def slotVerticesImpl (i : Fin {n})", 1),
            (r"def seedVertices : Fin \d+ →", f"def seedVertices : Fin {seeds} →", 1),
            (r"∀ t : Fin \d+, \(seedVertices", f"∀ t : Fin {seeds}, (seedVertices", 1),
            (r"∀ i : Fin \d+,\n", f"∀ i : Fin {n},\n", 2),
            (r"icoOrbitsCheck \d+ iOrbitCount", f"icoOrbitsCheck {seeds} iOrbitCount", 1),
            (r"seedCount := \d+\n", f"seedCount := {seeds}\n", 1)]:
        text, k = re.subn(pattern, lambda _, r=repl: r, text)
        if k != count:
            raise SystemExit(f"SolidModel.lean: expected {count} match(es) for {pattern}, got {k}")
    text = replace_def(text, f"def slotVertices : Fin {n} → Fin 3 → ℚ := ![", rows)
    text = replace_def(text, f"def seedVertices : Fin {seeds} → Fin 3 → ℚ := ![", rows[:seeds])
    args.solid_model.write_text(text, encoding="utf-8")
    print(f"updated {args.solid_model} from {args.exported}")


if __name__ == "__main__":
    main()
