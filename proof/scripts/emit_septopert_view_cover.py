#!/usr/bin/env python3
"""Emit Noperthedron/Septopert/ViewCoverData.lean: the 7-vertex solid's code
triangles (each with its projective root) and, per view domain (T1 in root 0,
T2 in root 1; codebdd.json's `view_domains`), a cover tree proving that the
domain's code triangles cover it (checked by `Septopert.ViewCover.Node.check`).

As scripts/emit_wedge_cover.py, but on the root's plane u . s = 1 with
s = AtlasProjectiveView.rootSign root (root 0: (1,1,1), root 1: (1,1,-1)):
`empty` and `leaf` certificates use s in place of (1,1,1), and leaves only
name triangles of the same root.

Usage: emit_septopert_view_cover.py --bdd <codebdd.json> <output.lean>
"""

from __future__ import annotations

import argparse
import ast
import json
import sys
from fractions import Fraction as F
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import emit_wedge_cover as W  # noqa: E402

ROOT_SIGN = {0: (F(1), F(1), F(1)), 1: (F(1), F(1), F(-1))}


def empty_witness(cons, s):
    c = W.cone_coeffs(cons, W.neg(s))
    if c is None:
        return None
    return c, F(1)


class Builder(W.Builder):
    def __init__(self, tris, allowed, s):
        super().__init__(tris)
        self.allowed = allowed
        self.s = s

    def inside(self, t, poly):
        return t in self.allowed and super().inside(t, poly)

    def build(self, cons, poly, depth=0):
        self.nodes += 1
        gens = cons + [self.s]
        if len(poly) == 0:
            w = empty_witness(cons, self.s)
            assert w is not None, "empty cell without witness"
            lam, kappa = w
            return ("empty", lam[:len(cons)], kappa)
        for t in range(len(self.tris)):
            if self.inside(t, poly):
                certs = []
                for e in self.tri_edges[t]:
                    c = W.cone_coeffs(gens, e)
                    if c is None:
                        break
                    certs.append((c[:len(cons)], c[len(cons)]))
                if len(certs) == 3:
                    return ("leaf", t, certs)
        best = None
        for t in self.allowed:
            for n in self.tri_edges[t]:
                vals = [W.dot(p, n) for p in poly]
                if min(vals) < 0 < max(vals):
                    pos = sum(1 for v in vals if v > 0)
                    negc = sum(1 for v in vals if v < 0)
                    score = min(pos, negc)
                    if best is None or score > best[0]:
                        best = (score, n)
        assert best is not None, (f"no splitting plane at depth {depth}: uncovered cell "
                                  f"{[tuple(float(x) for x in p) for p in poly]}")
        n = W.primitive(best[1])
        pos = self.build(cons + [n], W.clip(poly, n), depth + 1)
        negn = self.build(cons + [W.neg(n)], W.clip(poly, W.neg(n)), depth + 1)
        return ("split", n, pos, negn)


def parse(v):
    return ast.literal_eval(v) if isinstance(v, str) else v


def point(c):
    return tuple(F(c[k]) for k in "xyz")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--bdd", type=Path, required=True)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    d = json.load(open(args.bdd))
    tris, roots = [], []
    for code in d["codes"]:
        r = int(code["root"])
        for t in parse(code["triangles"]):
            tris.append(tuple(point(c) for c in t))
            roots.append(r)
    for t, r in zip(tris, roots):
        for c in t:
            assert W.dot(c, ROOT_SIGN[r]) == 1, "corner not on its root's plane"
    domains = d["view_domains"]
    assert [int(dm["root"]) for dm in domains] == [0, 1]
    expected = {0: ((F(1, 3), F(1, 3), F(1, 3)), (F(1, 2), F(1, 2), F(0)), (F(1), F(0), F(0))),
                1: ((F(1), F(0), F(0)), (F(1, 2), F(1, 2), F(0)), (F(0), F(0), F(-1)))}
    trees = []
    defs = []
    counter = [0]
    for dm in domains:
        r = int(dm["root"])
        base = tuple(point(c) for c in dm["corners"])
        # Lean's baseT1 / baseT2 (ViewCover.lean).
        assert base == expected[r], f"domain {r} corners {base} differ from ViewCover.baseT{r + 1}"
        allowed = [t for t in range(len(tris)) if roots[t] == r]
        b = Builder(tris, allowed, ROOT_SIGN[r])
        tree = b.build(list(W.edges(base)), list(base))
        print(f"root {r}: {len(allowed)} triangles, {b.nodes} tree nodes")
        trees.append(W.emit_node(tree, None, defs, counter, None))

    lines = [
        "module",
        "",
        "public import Noperthedron.Septopert.ViewCover",
        "",
        "@[expose] public section",
        "",
        "/-! Generated by scripts/emit_septopert_view_cover.py from codebdd.json",
        "(`codebdd.exe --model_file=septopert_model.txt`). -/",
        "",
        "namespace Noperthedron.Septopert.ViewCover",
        "",
        "open Noperthedron.Atlas.ProjectiveView",
        "open Noperthedron.Pipeline.WedgeCover (V Tri)",
        "",
        "/-- The code triangles with their projective roots: codes in order, each",
        "code's triangles in order (the code packs' triangle index t). -/",
        "def codeTriangles : Array (Fin 8 × Tri) := #[",
    ]
    tl = []
    for t, r in zip(tris, roots):
        tl.append(f"  ({r}, ![" + ", ".join(W.vec(c) for c in t) + "])")
    lines.append(",\n".join(tl))
    lines.append("]")
    lines.append("")
    lines.extend(d.replace(": Node :=", ": Node :=") for d in defs)
    lines.append("")
    lines.append(f"def coverTree0 : Node := {trees[0]}")
    lines.append(f"def coverTree1 : Node := {trees[1]}")
    lines.append("")
    lines.append("/-- The cover check (T1 by the root-0 triangles, T2 by the root-1 ones). -/")
    lines.append("def coverValid : Bool :=")
    lines.append("  coverTree0.check codeTriangles 0 (baseConstraints baseT1) &&")
    lines.append("    coverTree1.check codeTriangles 1 (baseConstraints baseT2)")
    lines.append("")
    lines.append("theorem coverValid_eq : coverValid = true := by decide +kernel")
    lines.append("")
    lines.append("/-- Every atlas pose with view in D′ lies over a code triangle (in that")
    lines.append("triangle's root, at view scale ≥ 1). -/")
    lines.append("theorem codeTriangles_cover (p : Noperthedron.Pipeline.AtlasPose ℝ)")
    lines.append("    (hdom : InC3vViewDomain (fun k => rotRM_mat p.θ p.φ 0 2 k)) :")
    lines.append("    ∃ t : ℕ, ∃ root : Fin 8, ∃ tri, codeTriangles[t]? = some (root, tri) ∧")
    lines.append("      1 ≤ Noperthedron.Pipeline.AtlasProjectiveView.viewScale root p ∧")
    lines.append("      InTriangle (toReal tri)")
    lines.append("        (Noperthedron.Pipeline.AtlasProjectiveView.normalizedView root p) := by")
    lines.append("  have h := coverValid_eq")
    lines.append("  simp only [coverValid, Bool.and_eq_true] at h")
    lines.append("  exact viewDomain_covered codeTriangles coverTree0 coverTree1 h.1 h.2 p hdom")
    lines.append("")
    lines.append("end Noperthedron.Septopert.ViewCover")
    lines.append("")
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.output} ({args.output.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
